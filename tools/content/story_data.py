def rw(gold=0, **items):
    return {"gold": gold, "items": items}


NPCS = {}
LOOKS = {}


def person(
    ident,
    name,
    en,
    age,
    gender,
    role,
    household,
    birthday,
    favorite,
    likes,
    dislikes,
    bio,
    talk,
    rain,
    birthday_line,
    after,
    romance,
    events,
    look,
):
    NPCS[ident] = {
        "name": name,
        "en": en,
        "age": age,
        "gender": gender,
        "role": role,
        "household": household,
        "birthday": {"season": birthday[0], "day": birthday[1]},
        "favorite": favorite,
        "likes": likes,
        "dislikes": dislikes,
        "sprite": "npc_" + ident,
        "portrait": "portrait_" + ident,
        "bio": bio,
        "talk": talk,
        "rain": rain,
        "birthday_line": birthday_line,
        "after": after,
        "romance": romance,
        "events": events,
    }
    LOOKS[ident] = look


def ev(ident, at, pages, reward):
    return {"id": "%s_%d" % (ident, at), "at": at, "reward": reward, "pages": pages}


def scenes_of(ident):
    return {e["id"]: e["pages"] for e in NPCS[ident]["events"]}


