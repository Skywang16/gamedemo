"""Every villager's daily routine, written as ordered rules (see docs/design/12-schedules.md).

A stop reads "HH:MM map/place | what they are doing". The first stop of every rule is 06:00 at
home. A rule's `when` may use: birthday, festival, weekdays (0 Mon .. 6 Sun), week (1-4),
seasons, weather, days, year_min, year_max, stage_min, stage_max. The first matching rule wins and
the last rule of each villager has no conditions. The place "festival" is the villager's spot at
the day's festival; "away" means not in town.
"""

WET = ["rain", "storm", "snow"]
FARM = "home_farm"


def rule(when, *stops):
    return {"when": when, "stops": list(stops)}


def festival(home, evening, evening_text, after="", after_text="", extra=None):
    stops = ["06:00 %s | 起床" % home, "09:00 festival | 参加节日"]
    if after:
        stops.append("14:30 %s | %s" % (after, after_text))
    stops += ["18:30 %s | %s" % (evening, evening_text), "22:00 %s | 回家休息" % home]
    return rule(dict({"festival": True}, **(extra or {})), *stops)


def birthday(home, morning, morning_text, noon, noon_text, evening, evening_text):
    return rule(
        {"birthday": True},
        "06:00 %s | 起床" % home,
        "09:00 %s | %s" % (morning, morning_text),
        "12:30 %s | %s" % (noon, noon_text),
        "18:00 %s | %s" % (evening, evening_text),
        "22:00 %s | 回家休息" % home,
    )


